"""XML Layout Rendering Stage for DDF Compiler.

Renders CDISC ODM v1.3.2 and OpenRosa XForms XML layouts via Jinja2 templates
and formats outputs via defusedxml.minidom.
"""

from __future__ import annotations

import hashlib
import os
from pathlib import Path

import defusedxml.minidom as minidom
from jinja2 import Environment, FileSystemLoader, select_autoescape

from packages.ddf.models import DDFStudyIR

# Set up Jinja2 environment default pointing to package templates directory
DEFAULT_TEMPLATE_DIR = os.path.join(
    os.path.dirname(os.path.dirname(__file__)), "templates"
)


def pretty_print(xml_string: str) -> str:
    """Format an XML string with clean indentation.

    Removes whitespace-only text nodes generated by Jinja2 templates before
    applying standard formatting via minidom to ensure expected line breaks.
    """
    dom = minidom.parseString(xml_string)
    for node in dom.getElementsByTagName("*"):
        for child in list(node.childNodes):
            if child.nodeType == 3 and not child.data.strip():
                node.removeChild(child)
    return dom.toprettyxml(indent="  ")


class XmlLayoutRendererStage:
    """Renders strongly-typed DDFStudyIR into formatted CDISC ODM and OpenRosa XML artifacts."""

    def __init__(self, template_dir: str | Path | None = None) -> None:
        tpl_dir = str(template_dir) if template_dir else DEFAULT_TEMPLATE_DIR
        self.env = Environment(
            loader=FileSystemLoader(tpl_dir),
            autoescape=select_autoescape(default_for_string=True, default=True),
        )

    def render(self, study_ir: DDFStudyIR) -> tuple[str, str, str]:
        """Renders intermediate representation into ODM and OpenRosa XML artifacts.

        Args:
            study_ir: Strongly typed intermediate representation of the study.

        Returns:
            Tuple of (odm_xml_string, openrosa_xml_string, openrosa_sha256_hash).
        """
        template_data = study_ir.to_template_dict()

        odm_template = self.env.get_template("odm_template.xml.j2")
        odm_raw = odm_template.render(**template_data)

        openrosa_template = self.env.get_template("openrosa_template.xml.j2")
        openrosa_raw = openrosa_template.render(**template_data)

        odm_str = pretty_print(odm_raw)
        openrosa_str = pretty_print(openrosa_raw)

        form_hash = hashlib.sha256(openrosa_str.encode("utf-8")).hexdigest()

        return odm_str, openrosa_str, form_hash
