using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;

using Npgsql;

namespace Cadence.Database;

/// <summary>
/// Renders the relational model of a <see cref="DbContext"/> as Markdown: one section per table with its columns,
/// keys, foreign keys, indexes and check constraints. The output depends only on the EF Core model, never on a live
/// database, and is deterministic, so a committed copy can be compared with a fresh one to detect drift.
/// </summary>
public static class SchemaDocumentation
{
    /// <summary>
    /// The PostgreSQL schema a context's unqualified tables live in: the first entry of its connection's search path
    /// (ADR-2447), or <c>public</c> when the connection sets none.
    /// </summary>
    public static string DefaultSchemaOf(DbContext context)
    {
        ArgumentNullException.ThrowIfNull(context);

        string? searchPath = context.Database.IsRelational()
            ? new NpgsqlConnectionStringBuilder(context.Database.GetConnectionString()).SearchPath
            : null;
        string? first = searchPath?.Split(',')[0].Trim();
        return string.IsNullOrEmpty(first) ? "public" : first;
    }

    /// <summary>
    /// Renders the design-time model of <paramref name="context"/>. Tables without an explicit schema are shown in
    /// <see cref="DefaultSchemaOf"/>.
    /// </summary>
    public static string Render(DbContext context, string title, string generatorCommand)
    {
        ArgumentNullException.ThrowIfNull(context);

        IModel model = context.GetService<IDesignTimeModel>().Model;
        return Render(model, context.GetType().FullName ?? context.GetType().Name, DefaultSchemaOf(context), title, generatorCommand);
    }

    /// <summary>Renders <paramref name="model"/>; exposed separately so it can be tested without a design-time factory.</summary>
    public static string Render(IModel model, string contextName, string defaultSchema, string title, string generatorCommand)
    {
        ArgumentNullException.ThrowIfNull(model);

        var tables = model.GetRelationalModel().Tables
            .OrderBy(t => t.Schema ?? defaultSchema, StringComparer.Ordinal)
            .ThenBy(t => t.Name, StringComparer.Ordinal)
            .ToList();

        var sb = new StringBuilder();
        sb.Append("# ").Append(title).Append("\n\n");
        sb.Append("<!-- Generated by `").Append(generatorCommand).Append("`. Do not edit by hand. -->\n\n");
        sb.Append("Generated from the EF Core model of `").Append(contextName).Append("`, not from a live database. ");
        sb.Append("Unqualified tables live in the `").Append(defaultSchema).Append("` schema.\n");

        if (tables.Count == 0)
        {
            sb.Append("\nThis context maps no tables.\n");
            return sb.ToString();
        }

        foreach (var table in tables)
        {
            RenderTable(sb, table, defaultSchema);
        }

        return sb.ToString();
    }

    private static void RenderTable(StringBuilder sb, ITable table, string defaultSchema)
    {
        sb.Append("\n## ").Append(QualifiedName(table, defaultSchema)).Append("\n\n");
        sb.Append("Entity: ").Append(Entities(table)).Append("\n\n");
        if (!string.IsNullOrWhiteSpace(table.Comment))
        {
            sb.Append(Cell(table.Comment)).Append("\n\n");
        }

        var pkColumns = table.PrimaryKey?.Columns.Select(c => c.Name).ToHashSet(StringComparer.Ordinal) ?? [];

        sb.Append("| Column | Type | Null | Default | Key |\n| --- | --- | --- | --- | --- |\n");
        foreach (var column in table.Columns.OrderBy(c => pkColumns.Contains(c.Name) ? 0 : 1).ThenBy(c => c.Name, StringComparer.Ordinal))
        {
            string key = pkColumns.Contains(column.Name) ? "PK" : "";
            string defaultValue = column.DefaultValueSql
                ?? column.ComputedColumnSql?.Insert(0, "computed: ")
                ?? (column.DefaultValue is { } value ? Convert.ToString(value, CultureInfo.InvariantCulture) : null)
                ?? "";

            sb.Append("| `").Append(column.Name).Append("` | `").Append(column.StoreType).Append("` | ")
                .Append(column.IsNullable ? "yes" : "no").Append(" | ")
                .Append(defaultValue.Length == 0 ? "" : "`" + Cell(defaultValue) + "`").Append(" | ")
                .Append(key).Append(" |\n");
        }

        var foreignKeys = table.ForeignKeyConstraints.OrderBy(f => f.Name, StringComparer.Ordinal).ToList();
        if (foreignKeys.Count > 0)
        {
            sb.Append("\nForeign keys:\n\n");
            foreach (var fk in foreignKeys)
            {
                sb.Append("- `").Append(fk.Name).Append("`: (").Append(Columns(fk.Columns)).Append(") references `")
                    .Append(QualifiedName(fk.PrincipalTable, defaultSchema)).Append("` (").Append(Columns(fk.PrincipalColumns))
                    .Append("), on delete ").Append(OnDelete(fk.OnDeleteAction)).Append('\n');
            }
        }

        var uniques = table.UniqueConstraints.Where(u => !u.GetIsPrimaryKey()).OrderBy(u => u.Name, StringComparer.Ordinal).ToList();
        var indexes = table.Indexes.OrderBy(i => i.Name, StringComparer.Ordinal).ToList();
        if (uniques.Count > 0 || indexes.Count > 0)
        {
            sb.Append("\nIndexes:\n\n");
            foreach (var unique in uniques)
            {
                sb.Append("- `").Append(unique.Name).Append("`: unique constraint (").Append(Columns(unique.Columns)).Append(")\n");
            }

            foreach (var index in indexes)
            {
                sb.Append("- `").Append(index.Name).Append("`: ").Append(index.IsUnique ? "unique " : "").Append('(')
                    .Append(Columns(index.Columns)).Append(')');
                if (!string.IsNullOrWhiteSpace(index.Filter))
                {
                    sb.Append(" where `").Append(Cell(index.Filter)).Append('`');
                }

                sb.Append('\n');
            }
        }

        var checks = table.CheckConstraints.OrderBy(c => c.Name, StringComparer.Ordinal).ToList();
        if (checks.Count > 0)
        {
            sb.Append("\nCheck constraints:\n\n");
            foreach (var check in checks)
            {
                sb.Append("- `").Append(check.Name).Append("`: `").Append(Cell(check.Sql)).Append("`\n");
            }
        }
    }

    private static string QualifiedName(ITable table, string defaultSchema) => $"{table.Schema ?? defaultSchema}.{table.Name}";

    private static string Entities(ITable table) =>
        string.Join(", ", table.EntityTypeMappings
            .Select(m => m.TypeBase.ClrType.Name)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(n => n, StringComparer.Ordinal)
            .Select(n => $"`{n}`"));

    private static string Columns(IEnumerable<IColumn> columns) => string.Join(", ", columns.Select(c => $"`{c.Name}`"));

    private static string OnDelete(ReferentialAction action) => action switch
    {
        ReferentialAction.Cascade => "cascade",
        ReferentialAction.Restrict => "restrict",
        ReferentialAction.SetNull => "set null",
        ReferentialAction.SetDefault => "set default",
        _ => "no action",
    };

    // Table cells and inline code cannot contain a raw pipe, backtick or line break.
    private static string Cell(string text) =>
        text.Replace("\r", "", StringComparison.Ordinal).Replace('\n', ' ').Replace("|", "\\|", StringComparison.Ordinal).Replace('`', '\'');
}
