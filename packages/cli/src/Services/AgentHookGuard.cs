using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace Cadence.Cli.Services;

/// <summary>
/// The decisions behind the agent lifecycle hooks (PRD-SYS-053): which tool calls are refused before they run. Pure
/// functions over the hook's JSON payload, so they are tested without an agent runtime.
/// </summary>
public static partial class AgentHookGuard
{
    /// <summary>Generated GxP documents that only <c>cadence gxp sync</c> may write (AGENTS.md).</summary>
    public static readonly IReadOnlyList<string> GeneratedGxPDocuments =
    [
        "docs/SDLC/Requirements_Traceability_Matrix.md",
        "docs/SDLC/IQ_OQ_PQ_Execution_Report.md",
        "docs/SDLC/runs/",
    ];

    private static readonly string[] CommandKeys = ["command", "commandline", "cmd"];
    private static readonly string[] PathKeys = ["file_path", "filepath", "targetfile", "path", "absolutepath", "notebook_path"];

    /// <summary>The shell command and file paths a tool call carries, whatever the agent runtime names them.</summary>
    public sealed record ToolCall(string? Command, IReadOnlyList<string> Paths);

    /// <summary>
    /// Reads a hook payload. Claude Code nests the arguments under <c>tool_input</c>; other runtimes put them at the
    /// top level or under other names, so every object in the payload is searched for the known keys.
    /// </summary>
    public static ToolCall ParsePayload(string json)
    {
        if (string.IsNullOrWhiteSpace(json))
        {
            return new ToolCall(null, []);
        }

        using var document = JsonDocument.Parse(json);
        string? command = null;
        var paths = new List<string>();
        Collect(document.RootElement, ref command, paths);
        return new ToolCall(command, paths);
    }

    /// <summary>Returns why a tool call must not run, or <see langword="null"/> when it may.</summary>
    public static string? RefusalReason(ToolCall call)
    {
        if (call.Paths.FirstOrDefault(IsGeneratedGxPDocument) is { } generated)
        {
            return $"{generated} is generated by `pnpm cadence gxp sync`; never edit it by hand.";
        }

        return call.Command is null ? null : CommandRefusalReason(call.Command);
    }

    /// <summary>Returns why a shell command must not run, or <see langword="null"/> when it may.</summary>
    public static string? CommandRefusalReason(string command)
    {
        if (NoVerifyRegex().IsMatch(command))
        {
            return "`--no-verify` skips the GxP pre-commit gates; fix what the hook reports instead.";
        }

        if (ForcePushToProtectedRegex().IsMatch(command) || DeleteProtectedBranchRegex().IsMatch(command))
        {
            return "Force-pushing, deleting or rewriting main is not allowed; work on a feature branch.";
        }

        if (HistoryRewriteRegex().IsMatch(command))
        {
            return "`git filter-branch` and `git filter-repo` rewrite shared history; ask a maintainer.";
        }

        if (RecursiveDeleteOfRootRegex().IsMatch(command))
        {
            return "Recursive deletion of the filesystem root, the home directory or the whole repository is not allowed.";
        }

        if (GitCleanIgnoredRegex().IsMatch(command))
        {
            return "`git clean -x` deletes ignored files such as .env and local certificates; name the paths to delete instead.";
        }

        if (GeneratedGxPDocuments.Any(doc => WritesTo(command, doc)))
        {
            return "The traceability matrix and IQ/OQ/PQ report are generated by `pnpm cadence gxp sync`; never write them by hand.";
        }

        return null;
    }

    /// <summary>Whether <paramref name="path"/> (absolute or repository-relative) is a generated GxP document.</summary>
    public static bool IsGeneratedGxPDocument(string path)
    {
        string normalized = path.Replace('\\', '/');
        return GeneratedGxPDocuments.Any(doc =>
            doc.EndsWith('/')
                ? normalized.StartsWith(doc, StringComparison.Ordinal) || normalized.Contains("/" + doc, StringComparison.Ordinal)
                : normalized == doc || normalized.EndsWith("/" + doc, StringComparison.Ordinal));
    }

    /// <summary>The reminder shown to the agent before it starts working (PRD-SYS-053 PreInvocation).</summary>
    public const string ComplianceReminder =
        "Cadence is GxP software (21 CFR Part 11). Follow AGENTS.md: inject IClock instead of reading the clock; keep " +
        "audit fields and the reason for change on every mutation; never add default secrets; tag only the requirement a " +
        "test proves and run `pnpm cadence gxp sync` after changing tags; never edit the generated RTM or IQ/OQ/PQ report; " +
        "update the documentation your change affects.";

    // A redirect, tee, cp or mv whose target is the document, or an in-place sed anywhere on a line that names it.
    private static bool WritesTo(string command, string document)
    {
        string doc = Regex.Escape(document);
        string target = $@"[""']?\S*{doc}";
        return Regex.IsMatch(command, $@"(>>?|\btee(\s+-a)?)\s*{target}", RegexOptions.None, RegexTimeout)
            || Regex.IsMatch(command, $@"\b(cp|mv)\b[^;&|]*\s{target}[""']?\s*($|;|&|\|)", RegexOptions.None, RegexTimeout)
            || Regex.IsMatch(command, $@"\bsed\s+(-[a-zA-Z]*i|--in-place)[^;&|]*{doc}", RegexOptions.None, RegexTimeout);
    }

    private static readonly TimeSpan RegexTimeout = TimeSpan.FromSeconds(1);

    private static void Collect(JsonElement element, ref string? command, List<string> paths)
    {
        switch (element.ValueKind)
        {
            case JsonValueKind.Object:
                foreach (JsonProperty property in element.EnumerateObject())
                {
                    string key = property.Name.ToLowerInvariant();
                    if (property.Value.ValueKind == JsonValueKind.String)
                    {
                        if (command is null && CommandKeys.Contains(key))
                        {
                            command = property.Value.GetString();
                        }
                        else if (PathKeys.Contains(key) && property.Value.GetString() is { Length: > 0 } path)
                        {
                            paths.Add(path);
                        }
                    }
                    else
                    {
                        Collect(property.Value, ref command, paths);
                    }
                }

                break;
            case JsonValueKind.Array:
                foreach (JsonElement item in element.EnumerateArray())
                {
                    Collect(item, ref command, paths);
                }

                break;
            default:
                break;
        }
    }

    [GeneratedRegex(@"(^|\s)--no-verify(\s|$)")]
    private static partial Regex NoVerifyRegex();

    [GeneratedRegex(@"\bgit\s+push\b(?=.*\s(--force(-with-lease)?(=\S+)?|-f)(\s|$))(?=.*(\s|:|\+)(main|master)(\s|$))")]
    private static partial Regex ForcePushToProtectedRegex();

    [GeneratedRegex(@"\bgit\s+(push\b.*(\s--delete|\s-d|\s:)\s*(main|master)(\s|$)|branch\s+-[dD]\s+(main|master)(\s|$)|push\s+\S+\s+:(main|master)(\s|$))")]
    private static partial Regex DeleteProtectedBranchRegex();

    [GeneratedRegex(@"\bgit\s+filter-(branch|repo)\b")]
    private static partial Regex HistoryRewriteRegex();

    [GeneratedRegex(@"\brm\s+(-[a-zA-Z]*r[a-zA-Z]*f?[a-zA-Z]*|-[a-zA-Z]*f[a-zA-Z]*r[a-zA-Z]*|--recursive)\b[^;&|]*\s(/|~|~/|\$HOME/?|\.|\./|\*|/\*)(\s|$|;|&|\|)")]
    private static partial Regex RecursiveDeleteOfRootRegex();

    [GeneratedRegex(@"\bgit\s+clean\s+-[a-zA-Z]*x")]
    private static partial Regex GitCleanIgnoredRegex();

}
