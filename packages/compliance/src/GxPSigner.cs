using System;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using System.Text;
using System.Text.RegularExpressions;

using Cadence.Kernel.Time;

namespace Cadence.Compliance;

public static partial class GxPSigner
{
    private const string StampHeading = "## Integrity Stamp";

    /// <summary>
    /// Appends a deterministic integrity stamp: the SHA-256 of the document body, marked as an unsigned working copy.
    /// Generated documents that are checked in use this, so regenerating them from the same tests and results gives
    /// the same file. It shows the file was not edited after generation; it is not an electronic signature. A release
    /// copy is signed by a named person with <see cref="SignGxpMarkdown"/> and that person's own certificate.
    /// </summary>
    public static string StampGxpMarkdown(string content)
    {
        var body = content.Trim();
        var hash = Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(body)));

        return
            $"{body}\n\n" +
            "---\n\n" +
            $"{StampHeading}\n\n" +
            "- **Status:** Unsigned working copy, generated by `dotnet cadence gxp sync`. Not an electronic signature.\n" +
            $"- **Content Hash (SHA-256):** {hash}\n";
    }

    /// <summary>
    /// Checks a document written by <see cref="StampGxpMarkdown"/>: false when the stamp is missing or the body no
    /// longer matches its hash, meaning the file was edited after it was generated.
    /// </summary>
    public static bool VerifyStamp(string stampedContent)
    {
        var normalized = stampedContent.Replace("\r\n", "\n", StringComparison.Ordinal);
        var stampStart = normalized.LastIndexOf("\n---\n\n" + StampHeading, StringComparison.Ordinal);
        if (stampStart < 0)
        {
            return false;
        }

        var match = StampHashPattern().Match(normalized[stampStart..]);
        if (!match.Success)
        {
            return false;
        }

        var body = normalized[..stampStart].Trim();
        var actual = Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(body)));
        return string.Equals(actual, match.Groups["hash"].Value, StringComparison.Ordinal);
    }

    [GeneratedRegex(@"\*\*Content Hash \(SHA-256\):\*\* (?<hash>[0-9a-f]{64})")]
    private static partial Regex StampHashPattern();

    public static string SignGxpMarkdown(
        string content,
        string? signerId = null,
        string signingReason = "GxP Qualification Execution Sign-Off",
        string? timestamp = null,
        RSA? privateKey = null,
        X509Certificate2? certificate = null,
        IClock? clock = null)
    {
        clock ??= SystemClock.Instance;
        signerId ??= Environment.GetEnvironmentVariable("GXP_SIGNER_ID") ?? "cadence-validation-runner";
        timestamp ??= clock.UtcNow.ToString("yyyy-MM-dd HH:mm:ss UTC", System.Globalization.CultureInfo.InvariantCulture);

        var contentBytes = Encoding.UTF8.GetBytes(content.Trim());
        var sha256Hash = Convert.ToHexStringLower(SHA256.HashData(contentBytes));

        var footerText =
            $"{content.TrimEnd()}\n\n" +
            $"---\n\n" +
            $"## Electronic Signature Block\n\n" +
            $"- **Signer Identity:** {signerId}\n" +
            $"- **Timestamp:** {timestamp}\n" +
            $"- **Meaning / Purpose:** {signingReason}\n" +
            $"- **Cryptographic Hash (SHA-256):** {sha256Hash}\n\n";

        if (certificate == null || privateKey == null)
        {
            var creds = Pkcs7Signer.GenerateSigningCredentials(signerId, clock);
            certificate ??= creds.Cert;
            privateKey ??= creds.Key;
        }

        var signer = new Pkcs7Signer(certificate, privateKey);
        var footerBytes = Encoding.UTF8.GetBytes(footerText.TrimEnd());
        var signedBytes = signer.SignDocument(footerBytes);

        return Encoding.UTF8.GetString(signedBytes);
    }
}
