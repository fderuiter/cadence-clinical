"""Domain models and canonical schemas for the Containerized Statistical Computing Environment (SCE).

Provides validated R and Python execution workspaces, package lockfile integrity verification (uv.lock, renv.lock),
cryptographically signed execution run manifests, 21 CFR Part 11 electronic signature blocks,
and formal database lock authorization gating for unblinded analyses.

Requirements: PRD-CDR-004, PRD-CDR-005, PRD-CDR-006, ADR-2199, 21 CFR Part 11
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field


class ExecutionLanguage(StrEnum):
    """Supported statistical computing languages."""

    PYTHON = "PYTHON"
    R = "R"


class ExecutionStatus(StrEnum):
    """Lifecycle status of a statistical computing run."""

    PENDING = "PENDING"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    TIMEOUT = "TIMEOUT"
    REJECTED = "REJECTED"


class PackageLockType(StrEnum):
    """Supported package dependency lockfile formats."""

    UV_LOCK = "UV_LOCK"
    RENV_LOCK = "RENV_LOCK"
    REQUIREMENTS_TXT = "REQUIREMENTS_TXT"


class LockValidationStatus(StrEnum):
    """Integrity and qualification status of a package lockfile."""

    VALID = "VALID"
    TAMPERED = "TAMPERED"
    INVALID_SYNTAX = "INVALID_SYNTAX"
    UNQUALIFIED_PACKAGE = "UNQUALIFIED_PACKAGE"
    UNVERIFIED = "UNVERIFIED"


class OutputArtifactType(StrEnum):
    """Standard statistical output artifact types."""

    TABLE = "TABLE"
    LISTING = "LISTING"
    FIGURE = "FIGURE"
    DATASET = "DATASET"
    LOG = "LOG"
    MANIFEST = "MANIFEST"


class SCEAction(StrEnum):
    """21 CFR Part 11 auditable operations within the statistical computing environment."""

    PROGRAM_CREATE = "PROGRAM_CREATE"
    PROGRAM_UPDATE = "PROGRAM_UPDATE"
    LOCK_VALIDATE = "LOCK_VALIDATE"
    LOCK_TOKEN_ISSUE = "LOCK_TOKEN_ISSUE"
    LOCK_TOKEN_REVOKE = "LOCK_TOKEN_REVOKE"
    EXECUTION_DISPATCH = "EXECUTION_DISPATCH"
    EXECUTION_COMPLETE = "EXECUTION_COMPLETE"
    MANIFEST_VERIFY = "MANIFEST_VERIFY"
    UNBLINDED_ANALYSIS_ACCESS = "UNBLINDED_ANALYSIS_ACCESS"
    UNBLINDED_ACCESS_DENIED = "UNBLINDED_ACCESS_DENIED"


class PackageEntry(BaseModel):
    """Individual qualified package dependency entry."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(
        ..., min_length=1, description="Package name (e.g. pandas, rtables)"
    )
    version: str = Field(..., min_length=1, description="Pinned package version string")
    checksum: str | None = Field(
        None, description="Cryptographic package digest (SHA-256)"
    )
    repository: str | None = Field(
        None, description="Source repository (e.g. PyPI, CRAN, Posit)"
    )
    is_qualified: bool = Field(
        True, description="Whether package is qualified in the GxP platform whitelist"
    )


class PackageLockValidationResult(BaseModel):
    """Result of lockfile parsing and cryptographic integrity assertion."""

    model_config = ConfigDict(extra="forbid")

    lock_type: PackageLockType = Field(..., description="Detected lockfile type")
    status: LockValidationStatus = Field(..., description="Validation outcome")
    lock_digest: str = Field(
        ..., description="Canonical SHA-256 hash of normalized lockfile content"
    )
    package_count: int = Field(
        ..., ge=0, description="Total number of pinned packages parsed"
    )
    packages: list[PackageEntry] = Field(
        default_factory=list, description="Parsed package definitions"
    )
    is_qualified: bool = Field(
        ..., description="Whether all packages meet platform qualification rules"
    )
    unqualified_packages: list[str] = Field(
        default_factory=list, description="List of unapproved packages if any"
    )
    details: str = Field(
        ..., description="Human-readable validation summary or error message"
    )


class OutputArtifact(BaseModel):
    """Individual statistical output artifact generated by an analytical run."""

    model_config = ConfigDict(extra="forbid")

    artifact_id: str = Field(
        default_factory=lambda: f"ART-{uuid.uuid4().hex[:10].upper()}",
        description="Unique artifact identifier",
    )
    name: str = Field(
        ...,
        min_length=1,
        description="Artifact filename (e.g. t_14_1_demographics.csv)",
    )
    artifact_type: OutputArtifactType = Field(
        ..., description="Categorized artifact type"
    )
    file_path: str = Field(..., description="Relative artifact path in run directory")
    mime_type: str = Field(..., description="MIME content type")
    size_bytes: int = Field(..., ge=0, description="File size in bytes")
    sha256_digest: str = Field(..., description="SHA-256 hash of artifact content")
    content_preview: str | None = Field(
        None, description="Text or base64 preview snippet"
    )


class ElectronicSignatureBlock(BaseModel):
    """21 CFR Part 11 compliant electronic signature block."""

    model_config = ConfigDict(extra="forbid")

    signer_id: str = Field(..., description="Unique user ID of executing statistician")
    signer_role: str = Field(..., description="Regulatory role of statistician")
    signed_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="Timestamp of electronic signature",
    )
    signature_meaning: str = Field(
        "Electronic signature confirming authoring, validation, and execution of statistical run",
        description="Regulatory intent of the signature",
    )
    hmac_signature: str = Field(
        ..., description="HMAC-SHA256 signature sealing the execution run"
    )


class ExecutionSandboxConfig(BaseModel):
    """Resource bounds and security controls for containerized statistical execution."""

    model_config = ConfigDict(extra="forbid")

    max_memory_mb: int = Field(
        2048, ge=256, le=16384, description="Maximum RAM allocated to sandbox (MB)"
    )
    timeout_seconds: int = Field(
        300, ge=1, le=3600, description="Execution timeout limit in seconds"
    )
    network_isolated: bool = Field(
        True, description="Enforces zero outbound network egress"
    )
    filesystem_readonly_root: bool = Field(
        True, description="Read-only root filesystem with ephemeral workspace"
    )
    max_output_bytes: int = Field(
        10_485_760, description="Maximum stdout/stderr capture buffer size (10 MB)"
    )
    docker_image_digest: str = Field(
        "sha256:cadence-sce-r4.4-py3.14-validated-base-2026",
        description="Immutable container base image digest",
    )
    python_version: str = Field("3.14.0", description="Pinned Python runtime version")
    r_version: str = Field("4.4.2", description="Pinned R runtime version")
    environment_variables: dict[str, str] = Field(
        default_factory=dict, description="Safe runtime environment variables"
    )


class DatabaseLockAuthToken(BaseModel):
    """Formal database lock authorization token gating unblinded statistical analysis."""

    model_config = ConfigDict(extra="forbid")

    token_id: str = Field(
        ..., description="Unique authorization token ID (e.g. DBLOCK-AUTH-...)"
    )
    study_id: str = Field(..., description="Target study identifier")
    lock_id: str = Field(..., description="Associated database lock reference")
    milestone: str = Field(
        ..., description="Milestone tier (e.g. INTERIM_ANALYSIS_1, DATABASE_LOCK)"
    )
    issued_to: str = Field(
        ..., description="Authorized statistician or committee lead user ID"
    )
    authorized_roles: list[str] = Field(..., description="Permitted unblinded roles")
    issued_at: datetime = Field(..., description="Issuance timestamp")
    expires_at: datetime = Field(..., description="Token expiration timestamp")
    signature_hash: str = Field(
        ..., description="Cryptographic HMAC signature of token claims"
    )
    is_revoked: bool = Field(
        False, description="Whether token has been explicitly revoked"
    )
    reason: str = Field(
        ..., description="Regulatory justification for unblinded analysis access"
    )


class StatisticalProgram(BaseModel):
    """Version-controlled, validated statistical program definition."""

    model_config = ConfigDict(extra="forbid")

    program_id: str = Field(
        default_factory=lambda: f"PROG-{uuid.uuid4().hex[:10].upper()}",
        description="Unique program identifier",
    )
    study_id: str = Field(
        ..., min_length=1, description="Associated clinical study identifier"
    )
    name: str = Field(
        ..., min_length=1, description="Program script filename (e.g. t_14_1_demog.py)"
    )
    title: str = Field(..., min_length=1, description="Descriptive program title")
    description: str = Field(
        "", description="Detailed explanation of statistical analysis"
    )
    language: ExecutionLanguage = Field(
        ..., description="Runtime language (PYTHON or R)"
    )
    version: str = Field("1.0.0", description="Semantic version string")
    source_code: str = Field(
        ..., min_length=1, description="Validated script source code"
    )
    code_hash: str = Field(..., description="SHA-256 hash of the script source code")
    lockfile_content: str | None = Field(
        None, description="Raw package lockfile text (uv.lock / renv.lock)"
    )
    lock_type: PackageLockType = Field(
        PackageLockType.UV_LOCK, description="Lockfile format"
    )
    lock_digest: str = Field(
        ..., description="SHA-256 hash of normalized package lockfile"
    )
    target_domain: str | None = Field(
        None, description="Target CDISC output domain (e.g. ADSL, TLF-14.1)"
    )
    created_by: str = Field(..., description="Authoring biostatistician user ID")
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC), description="Creation timestamp"
    )
    reason_for_change: str = Field(
        "Initial program authoring", description="GxP change rationale (21 CFR Part 11)"
    )


class ExecutionRunManifest(BaseModel):
    """Cryptographically signed, bit-for-bit reproducible execution run manifest (21 CFR Part 11)."""

    model_config = ConfigDict(extra="forbid")

    manifest_id: str = Field(
        default_factory=lambda: f"MAN-{uuid.uuid4().hex[:12].upper()}",
        description="Unique manifest identifier",
    )
    run_id: str = Field(..., description="Associated execution run identifier")
    study_id: str = Field(..., description="Clinical study identifier")
    program_id: str = Field(..., description="Executed statistical program ID")
    program_name: str = Field(..., description="Program filename")
    program_version: str = Field(..., description="Executed program version")
    snapshot_id: str = Field(
        ..., description="Version-pinned clinical data snapshot ID"
    )
    snapshot_version_tag: str = Field(..., description="Data snapshot version tag")
    snapshot_digest: str = Field(
        ..., description="SHA-256 seal of input pooled dataset snapshot"
    )
    language: ExecutionLanguage = Field(..., description="Execution runtime language")
    script_code_digest: str = Field(
        ..., description="SHA-256 digest of executed source code"
    )
    lockfile_digest: str = Field(
        ..., description="SHA-256 digest of verified package lockfile"
    )
    container_image_digest: str = Field(..., description="Base container image digest")
    execution_start: datetime = Field(..., description="Execution start timestamp")
    execution_end: datetime = Field(..., description="Execution completion timestamp")
    duration_ms: float = Field(
        ..., ge=0.0, description="Total execution duration in milliseconds"
    )
    exit_code: int = Field(..., description="Process exit code (0 = success)")
    status: ExecutionStatus = Field(..., description="Final execution outcome status")
    stdout_capture: str = Field(
        "", description="Standard output captured from execution sandbox"
    )
    stderr_capture: str = Field(
        "", description="Standard error captured from execution sandbox"
    )
    output_artifacts: list[OutputArtifact] = Field(
        default_factory=list,
        description="List of generated output artifacts with SHA-256 digests",
    )
    output_artifacts_digest: str = Field(
        ...,
        description="Combined Merkle/SHA-256 digest of all generated output artifacts",
    )
    is_unblinded_run: bool = Field(
        False,
        description="Whether unblinded treatment arms were accessed during analysis",
    )
    database_lock_token_id: str | None = Field(
        None,
        description="Database lock authorization token if unblinded analysis executed",
    )
    executed_by: str = Field(..., description="Executing biostatistician user ID")
    executed_by_role: str = Field(..., description="Regulatory role of executing user")
    signature_block: ElectronicSignatureBlock = Field(
        ..., description="21 CFR Part 11 electronic signature block"
    )
    manifest_sha256_seal: str = Field(
        ..., description="Root SHA-256 seal of this complete execution run manifest"
    )
