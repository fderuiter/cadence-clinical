"""Unit and integration tests for the Fileshare FFmpeg video transcoding worker.

Requirements: PRD-SYS-001, PRD-DOC-001, PRD-DOC-002, PRD-DOC-003
"""

import tempfile
import uuid
from datetime import UTC, datetime
from pathlib import Path

import pytest

from apps.fileshare.domain.models import FileRecord, TranscodeStatus
from apps.fileshare.workers.transcode_worker import (
    VideoTranscodeWorker,
    execute_ffmpeg_transcode,
)
from packages.testing.fakes import InMemoryRepository, InMemoryStoragePort


@pytest.fixture
def fake_file_repo() -> InMemoryRepository[FileRecord]:
    """In-memory repository fake for FileRecord entities."""
    return InMemoryRepository[FileRecord]()


@pytest.fixture
def fake_storage() -> InMemoryStoragePort:
    """In-memory storage port fake."""
    return InMemoryStoragePort()


@pytest.mark.asyncio
async def test_worker_successful_transcode_state_machine(
    fake_file_repo: InMemoryRepository[FileRecord],
    fake_storage: InMemoryStoragePort,
):
    """Verify video worker transitions FileRecord from PENDING to IN_PROGRESS to READY.

    @req:PRD-SYS-001
    @req:PRD-DOC-001
    """
    file_id = str(uuid.uuid4())
    object_key = f"tenant_trial_01/STUDY-101/{file_id}/surgical_procedure.mp4"
    video_bytes = b"\x00\x00\x00\x18ftypmp42\x00\x00\x00\x00mp42isom" + b"\x00" * 1024

    # Seed object store and database
    await fake_storage.put_object(
        key=object_key, data=video_bytes, content_type="video/mp4"
    )

    record = FileRecord(
        id=file_id,
        study_id="STUDY-101",
        site_id="SITE-01",
        filename="surgical_procedure.mp4",
        mime_type="video/mp4",
        size_bytes=len(video_bytes),
        object_key=object_key,
        uploaded_by="surgeon_crc",
        uploaded_at=datetime.now(UTC),
        transcode_status=TranscodeStatus.PENDING,
        created_at=datetime.now(UTC),
        created_by="surgeon_crc",
        reason_for_change="Surgical procedure recording upload",
    )
    await fake_file_repo.save(record)

    worker = VideoTranscodeWorker(
        file_repo=fake_file_repo,
        storage_port=fake_storage,
    )

    result = await worker.transcode_file(file_id)

    # Verify result state
    assert result.transcode_status == TranscodeStatus.READY
    assert result.hls_manifest_key == f"hls/{file_id}/master.m3u8"
    assert result.transcode_error is None

    # Verify storage artifacts
    assert await fake_storage.exists(f"hls/{file_id}/master.m3u8") is True
    assert await fake_storage.exists(f"hls/{file_id}/360p.m3u8") is True
    assert await fake_storage.exists(f"hls/{file_id}/720p.m3u8") is True
    assert await fake_storage.exists(f"hls/{file_id}/1080p.m3u8") is True
    assert await fake_storage.exists(f"hls/{file_id}/360p_000.ts") is True

    # Verify master manifest content
    master_bytes, _ = await fake_storage.get_object(f"hls/{file_id}/master.m3u8")
    master_text = master_bytes.decode("utf-8")
    assert "#EXTM3U" in master_text
    assert "360p.m3u8" in master_text
    assert "720p.m3u8" in master_text
    assert "1080p.m3u8" in master_text


@pytest.mark.asyncio
async def test_worker_failure_transcode_state_machine(
    fake_file_repo: InMemoryRepository[FileRecord],
    fake_storage: InMemoryStoragePort,
):
    """Verify video worker transitions FileRecord to FAILED when FFmpeg executor encounters an error.

    @req:PRD-SYS-001
    @req:PRD-DOC-001
    """
    file_id = str(uuid.uuid4())
    object_key = f"tenant_trial_01/STUDY-101/{file_id}/corrupted.mp4"
    await fake_storage.put_object(
        key=object_key, data=b"bad-data", content_type="video/mp4"
    )

    record = FileRecord(
        id=file_id,
        study_id="STUDY-101",
        site_id="SITE-01",
        filename="corrupted.mp4",
        mime_type="video/mp4",
        size_bytes=8,
        object_key=object_key,
        uploaded_by="user_01",
        uploaded_at=datetime.now(UTC),
        transcode_status=TranscodeStatus.PENDING,
        created_at=datetime.now(UTC),
        created_by="user_01",
        reason_for_change="Corrupted video upload",
    )
    await fake_file_repo.save(record)

    def failing_executor(input_p: Path, output_d: Path):
        raise RuntimeError(
            "FFmpeg decode error: Invalid data found when processing input"
        )

    worker = VideoTranscodeWorker(
        file_repo=fake_file_repo,
        storage_port=fake_storage,
        ffmpeg_executor=failing_executor,
    )

    result = await worker.transcode_file(file_id)

    assert result.transcode_status == TranscodeStatus.FAILED
    assert result.hls_manifest_key is None
    assert "FFmpeg decode error" in (result.transcode_error or "")


@pytest.mark.asyncio
async def test_execute_ffmpeg_transcode_package_generation():
    """Verify HLS package structure generated by transcode pipeline.

    @req:PRD-SYS-001
    @req:PRD-DOC-001
    """
    with tempfile.TemporaryDirectory() as tmp_dir_str:
        tmp_dir = Path(tmp_dir_str)
        input_video = tmp_dir / "sample.mp4"
        input_video.write_bytes(b"\x00" * 1024)
        output_dir = tmp_dir / "hls"
        output_dir.mkdir(parents=True, exist_ok=True)

        await execute_ffmpeg_transcode(input_video, output_dir)

        master_pl = output_dir / "master.m3u8"
        assert master_pl.exists()
        content = master_pl.read_text(encoding="utf-8")
        assert "#EXTM3U" in content
        assert "360p.m3u8" in content
        assert "720p.m3u8" in content
        assert "1080p.m3u8" in content

        p360 = output_dir / "360p.m3u8"
        assert p360.exists()
        p360_content = p360.read_text(encoding="utf-8")
        assert "#EXT-X-TARGETDURATION" in p360_content
        assert "360p_000.ts" in p360_content
