def count_syllables_word(word: str) -> int:
    """Phonetic syllable counting heuristic for English language words."""
    cleaned = word.lower().strip(" \t\n\r.:,;?!\"'()[]{}/*-")
    if not cleaned:
        return 0

    vowels = "aeiouy"
    count = 0
    prev_char_is_vowel = False

    for char in cleaned:
        is_vowel = char in vowels
        if is_vowel and not prev_char_is_vowel:
            count += 1
        prev_char_is_vowel = is_vowel

    # Adjust for silent trailing 'e'
    if cleaned.endswith("e"):
        count -= 1

    # Adjust for "-le" after consonants forming a syllabic consonant (e.g. 'table', 'simple')
    if cleaned.endswith("le") and len(cleaned) > 2 and cleaned[-3] not in vowels:
        count += 1

    # Adjust for common "-ed" past tense endings
    if (
        cleaned.endswith("ed")
        and not (cleaned.endswith("ted") or cleaned.endswith("ded"))
        and count > 1
    ):
        count -= 1

    if count <= 0:
        count = 1
    return count


def is_dale_chall_familiar(word: str) -> bool:
    """Determines whether a word is recognized as familiar under the Dale-Chall standard."""
    w = word.lower().strip(" \t\n\r.:,;?!\"'()[]{}/*-")
    if not w:
        return True

    # Direct match in standard list
    if w in DALE_CHALL_FAMILIAR_WORDS:
        return True

    # Numeric strings are familiar
    if w.isdigit():
        return True

    # Common English inflection stems
    # Regular plurals & third person singular (-s, -es)
    if w.endswith("ies") and (w[:-3] + "y") in DALE_CHALL_FAMILIAR_WORDS:
        return True
    if w.endswith("es") and w[:-2] in DALE_CHALL_FAMILIAR_WORDS:
        return True
    if w.endswith("s") and w[:-1] in DALE_CHALL_FAMILIAR_WORDS:
        return True

    # Past tense (-ed, -d)
    if w.endswith("ed") and w[:-2] in DALE_CHALL_FAMILIAR_WORDS:
        return True
    if w.endswith("ed") and (w[:-1]) in DALE_CHALL_FAMILIAR_WORDS:
        return True

    # Gerund (-ing)
    if w.endswith("ing") and w[:-3] in DALE_CHALL_FAMILIAR_WORDS:
        return True
    if w.endswith("ing") and (w[:-3] + "e") in DALE_CHALL_FAMILIAR_WORDS:
        return True

    # Adverbs (-ly)
    if w.endswith("ly") and w[:-2] in DALE_CHALL_FAMILIAR_WORDS:
        return True

    # Comparatives (-er, -est)
    if w.endswith("er") and w[:-2] in DALE_CHALL_FAMILIAR_WORDS:
        return True
    return bool(w.endswith("est") and w[:-3] in DALE_CHALL_FAMILIAR_WORDS)


def tokenize_sentences(text: str) -> list[str]:
    """Tokenizes narrative text into sentences using regex boundary detection."""
    clean_text = text.strip()
    if not clean_text:
        return []
    # Split on sentence terminals while keeping sensible chunks
    raw_sentences = re.split(r"(?<=[.!?])\s+", clean_text)
    sentences = [s.strip() for s in raw_sentences if s.strip()]
    return sentences if sentences else [clean_text]


def tokenize_words(text: str) -> list[str]:
    """Tokenizes narrative text into discrete words stripping punctuation and HTML tags."""
    # Strip HTML tags
    clean_text = re.sub(r"<[^>]+>", " ", text)
    # Extract alphanumeric and hyphenated words
    words = re.findall(r"\b[a-zA-Z0-9'-]+\b", clean_text)
    return [w for w in words if w.strip()]


def interpret_reading_ease(fre: float) -> str:
    """Returns qualitative interpretation of Flesch Reading Ease score."""
    if fre >= 90:
        return "Very Easy (5th grade reading level)"
    if fre >= 80:
        return "Easy (6th grade reading level)"
    if fre >= 70:
        return "Fairly Easy (7th grade reading level)"
    if fre >= 60:
        return "Standard (8th-9th grade reading level)"
    if fre >= 50:
        return "Fairly Difficult (10th-12th grade / High School)"
    if fre >= 30:
        return "Difficult (College level)"
    return "Very Confusing (Professional / Post-graduate level)"


def interpret_dale_chall_grade_level(score: float) -> str:
    """Returns standard Dale-Chall grade equivalent level string."""
    if score <= 4.9:
        return "Grade 4 and below"
    if score <= 5.9:
        return "Grades 5-6"
    if score <= 6.9:
        return "Grades 7-8"
    if score <= 7.9:
        return "Grades 9-10"
    if score <= 8.9:
        return "Grades 11-12"
    if score <= 9.9:
        return "Grades 13-15 (College)"
    return "Grades 16+ (College Graduate)"
